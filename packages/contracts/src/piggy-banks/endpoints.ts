import { z } from "zod";
import { defineEndpoint } from "../api.js";
import { listMetaSchema } from "../list.js";
import {
  bulkDepositBodySchema,
  createPiggyBankBodySchema,
  depositToPiggyBankBodySchema,
  goalPiggyBanksParamsSchema,
  listPiggyBanksQuerySchema,
  movePiggyBankFundsBodySchema,
  piggyBankIdParamsSchema,
  piggyBankMovementsQuerySchema,
  piggyBanksReportQuerySchema,
  runPiggyBankAccrualBodySchema,
  setGoalPiggyBanksBodySchema,
  setPiggyBankBalanceBodySchema,
  updatePiggyBankBodySchema,
  withdrawFromPiggyBankBodySchema,
} from "./requests.js";
import {
  goalPiggyBanksSchema,
  goalPiggyPlanSchema,
  piggyBankAccrualResultSchema,
  piggyBankDetailSchema,
  piggyBankMovementSchema,
  piggyBankOperationSchema,
  piggyBanksOverviewSchema,
  piggyBanksReportSchema,
} from "./resource.js";

export const piggyBanksEndpoints = {
  /** Piggy banks plus, per parent account, the real balance, the free part and the piggy total. */
  list: defineEndpoint({
    method: "get",
    path: "/piggy-banks",
    query: listPiggyBanksQuerySchema,
    response: piggyBanksOverviewSchema,
    status: 200,
  }),
  report: defineEndpoint({
    method: "get",
    path: "/piggy-banks/report",
    query: piggyBanksReportQuerySchema,
    response: piggyBanksReportSchema,
    status: 200,
  }),
  get: defineEndpoint({
    method: "get",
    path: "/piggy-banks/:id",
    params: piggyBankIdParamsSchema,
    response: piggyBankDetailSchema,
    status: 200,
  }),
  create: defineEndpoint({
    method: "post",
    path: "/piggy-banks",
    body: createPiggyBankBodySchema,
    response: piggyBankDetailSchema,
    status: 201,
  }),
  update: defineEndpoint({
    method: "patch",
    path: "/piggy-banks/:id",
    params: piggyBankIdParamsSchema,
    body: updatePiggyBankBodySchema,
    response: piggyBankDetailSchema,
    status: 200,
  }),
  /** Only a piggy bank with a zero balance can be archived (409 otherwise). */
  archive: defineEndpoint({
    method: "post",
    path: "/piggy-banks/:id/archive",
    params: piggyBankIdParamsSchema,
    response: piggyBankDetailSchema,
    status: 200,
  }),
  unarchive: defineEndpoint({
    method: "post",
    path: "/piggy-banks/:id/unarchive",
    params: piggyBankIdParamsSchema,
    response: piggyBankDetailSchema,
    status: 200,
  }),
  movements: defineEndpoint({
    method: "get",
    path: "/piggy-banks/:id/movements",
    params: piggyBankIdParamsSchema,
    query: piggyBankMovementsQuerySchema,
    response: z.array(piggyBankMovementSchema),
    meta: listMetaSchema(),
    status: 200,
  }),
  deposit: defineEndpoint({
    method: "post",
    path: "/piggy-banks/:id/deposit",
    params: piggyBankIdParamsSchema,
    body: depositToPiggyBankBodySchema,
    response: piggyBankOperationSchema,
    status: 201,
  }),
  withdraw: defineEndpoint({
    method: "post",
    path: "/piggy-banks/:id/withdraw",
    params: piggyBankIdParamsSchema,
    body: withdrawFromPiggyBankBodySchema,
    response: piggyBankOperationSchema,
    status: 201,
  }),
  bulkDeposit: defineEndpoint({
    method: "post",
    path: "/piggy-banks/bulk-deposit",
    body: bulkDepositBodySchema,
    response: piggyBankOperationSchema,
    status: 201,
  }),
  move: defineEndpoint({
    method: "post",
    path: "/piggy-banks/move",
    body: movePiggyBankFundsBodySchema,
    response: piggyBankOperationSchema,
    status: 201,
  }),
  setBalance: defineEndpoint({
    method: "post",
    path: "/piggy-banks/:id/balance",
    params: piggyBankIdParamsSchema,
    body: setPiggyBankBalanceBodySchema,
    response: piggyBankOperationSchema,
    status: 201,
  }),
  /** Runs the daily accrual now (the schedule runs it anyway); safe to repeat. */
  accrue: defineEndpoint({
    method: "post",
    path: "/piggy-banks/accrue",
    body: runPiggyBankAccrualBodySchema,
    response: piggyBankAccrualResultSchema,
    status: 200,
  }),
  goalLinks: defineEndpoint({
    method: "get",
    path: "/goals/:id/piggy-banks",
    params: goalPiggyBanksParamsSchema,
    response: goalPiggyBanksSchema,
    status: 200,
  }),
  setGoalLinks: defineEndpoint({
    method: "put",
    path: "/goals/:id/piggy-banks",
    params: goalPiggyBanksParamsSchema,
    body: setGoalPiggyBanksBodySchema,
    response: goalPiggyBanksSchema,
    status: 200,
  }),
  goalPlan: defineEndpoint({
    method: "get",
    path: "/goals/:id/piggy-plan",
    params: goalPiggyBanksParamsSchema,
    response: goalPiggyPlanSchema,
    status: 200,
  }),
} as const;
